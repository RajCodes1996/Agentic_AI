
from pathlib import Path
from datetime import datetime
import re


REPORT_DIR = Path("outputs/reports")


def generate_markdown_report(
    topic: str,
    analysis: str,
    evidence: list
) -> str:

    date = datetime.now().strftime("%Y-%m-%d %H:%M")

    source_section = []

    for number, source in enumerate(evidence, start=1):

        source_section.append(
            f"{number}. [{source['title']}]"
            f"({source['url']})"
        )

    report = f"""
# AI Research Report

**Topic:** {topic}

**Generated:** {date}

---

## Research Analysis

{analysis}

---

## Sources

{chr(10).join(source_section)}

---

*Generated by AI Research Assistant.*
"""

    return report


def save_report(topic: str, report: str) -> str:

    REPORT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    safe_topic = re.sub(
        r"[^a-zA-Z0-9_-]+",
        "_",
        topic
    ).strip("_")

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    filename = f"{safe_topic}_{timestamp}.md"

    file_path = REPORT_DIR / filename

    file_path.write_text(
        report,
        encoding="utf-8"
    )

    return str(file_path)